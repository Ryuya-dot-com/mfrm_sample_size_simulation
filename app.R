build_tradeoff_ggplot <- function(res_obj, secondary_metric = c("RaterRMSE", "RaterCov95", "ScaleRatio")) {
  secondary_metric <- match.arg(secondary_metric)
  df <- res_obj$summary
  plan_levels <- unique(res_obj$grid$plan_label[order(res_obj$grid$total_ratings)])
  df$PlanFactor <- factor(df$Plan, levels = plan_levels)
  df$Estimator  <- factor(df$Estimator, levels = c("MML", "JML"))

  sec_label <- switch(
    secondary_metric,
    RaterRMSE  = "Rater severity RMSE (logits)",
    RaterCov95 = "Rater 95% CI coverage (%)",
    ScaleRatio = "Structural scale ratio (1.0 = unbiased)"
  )
  sec_ref <- switch(
    secondary_metric,
    RaterRMSE  = res_obj$targets$target_rater_rmse,
    RaterCov95 = 95,
    ScaleRatio = 1.0
  )

  mk_tip <- function(metric_name, val_str) {
    sprintf(
      "<b>%s (%s)</b><br>Ratings: %d (%.0f / rater)<br>%s: %s<br>Decision: %s",
      df$Plan, df$Estimator, df$total_ratings, df$ratings_per_rater,
      metric_name, val_str, df$Decision
    )
  }

  long_df <- rbind(
    data.frame(
      PlanFactor = df$PlanFactor,
      Estimator  = df$Estimator,
      Panel      = "Person reliability (true-score r^2)",
      Value      = df$PersonRel,
      Target     = res_obj$targets$target_rel,
      Tooltip    = mk_tip("Person r^2", ifelse(is.na(df$PersonRel), "NA", sprintf("%.3f", df$PersonRel))),
      stringsAsFactors = FALSE
    ),
    data.frame(
      PlanFactor = df$PlanFactor,
      Estimator  = df$Estimator,
      Panel      = sec_label,
      Value      = df[[secondary_metric]],
      Target     = sec_ref,
      Tooltip    = mk_tip(sec_label, ifelse(is.na(df[[secondary_metric]]), "NA", sprintf("%.3f", df[[secondary_metric]]))),
      stringsAsFactors = FALSE
    )
  )
  long_df$Panel <- factor(long_df$Panel, levels = c("Person reliability (true-score r^2)", sec_label))

  dodge <- position_dodge(width = 0.20)
  suppressWarnings(
    ggplot(long_df, aes(
      x = PlanFactor, y = Value, color = Estimator, shape = Estimator,
      linetype = Estimator, group = Estimator, text = Tooltip
    )) +
      geom_hline(aes(yintercept = Target), linetype = "dashed", color = "#666666", linewidth = 0.45) +
      geom_line(linewidth = 0.72, alpha = 0.82, position = dodge, na.rm = TRUE) +
      geom_point(size = 2.9, alpha = 0.92, position = dodge, na.rm = TRUE) +
      facet_wrap(~ Panel, ncol = 1, scales = "free_y") +
      scale_color_manual(values = c("MML" = "#0072B2", "JML" = "#D55E00"), drop = FALSE) +
      scale_shape_manual(values = c("MML" = 16, "JML" = 17), drop = FALSE) +
      scale_linetype_manual(values = c("MML" = "solid", "JML" = "dotdash"), drop = FALSE) +
      labs(x = "Candidate rating plan (ordered by total rating workload)", y = NULL) +
      theme_bw(base_size = 11.5) +
      theme(
        panel.grid.minor = element_blank(),
        panel.grid.major = element_line(color = "#ECECEC", linewidth = 0.35),
        strip.background = element_rect(fill = "#F5F5F5", color = "#CCCCCC"),
        strip.text = element_text(face = "bold", size = 11),
        axis.text.x = element_text(angle = 14, hjust = 1),
        legend.position = "bottom",
        legend.title = element_blank(),
        legend.key.width = grid::unit(24, "pt")
      )
  )
}

build_tradeoff_plotly <- function(res_obj, secondary_metric = "RaterRMSE") {
  p <- build_tradeoff_ggplot(res_obj, secondary_metric = secondary_metric)
  ply <- plotly::ggplotly(p, tooltip = "text")
  # Deduplicate faceted legend entries generated by ggplotly
  seen <- character()
  for (i in seq_along(ply$x$data)) {
    nm <- ply$x$data[[i]]$name %||% ""
    clean_nm <- gsub("^\\((.*),[0-9]+\\)$", "\\1", nm)
    ply$x$data[[i]]$name <- clean_nm
    ply$x$data[[i]]$legendgroup <- clean_nm
    if (!nzchar(clean_nm) || clean_nm %in% seen) {
      ply$x$data[[i]]$showlegend <- FALSE
    } else {
      seen <- c(seen, clean_nm)
    }
  }
  plotly::layout(ply, legend = list(orientation = "h", x = 0.35, y = -0.18))
}

