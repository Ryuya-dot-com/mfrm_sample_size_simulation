server <- function(input, output, session) {
  n_extra <- reactiveVal(1L)

  observeEvent(input$add_facet, {
    if (n_extra() < 6L) n_extra(n_extra() + 1L)
  })
  observeEvent(input$rem_facet, {
    if (n_extra() > 0L) n_extra(n_extra() - 1L)
  })

  # Keep m <= R and k <= min(P) dynamically synchronized
  observeEvent(input$n_rater, {
    cur <- input$raters_per_person %||% 2L
    updateSliderInput(session, "raters_per_person", max = input$n_rater, value = min(cur, input$n_rater))
  })
  observeEvent(input$p_range, {
    min_p <- min(input$p_range)
    cur_k <- input$anchor_persons %||% 6L
    updateSliderInput(session, "anchor_persons", max = min_p, value = min(cur_k, min_p))
  })

  output$extraFacetsUI <- renderUI({
    k <- n_extra()
    if (k == 0L) return(NULL)
    cards <- lapply(seq_len(k), function(i) {
      cat_def <- if (i <= length(default_facet_catalog)) default_facet_catalog[[i]] else list(name = paste0("Facet", i + 2L), levels = 2L, sd = 0.25)
      cur_nm  <- isolate(input[[paste0("ef_name_", i)]])   %||% cat_def$name
      cur_lvl <- isolate(input[[paste0("ef_levels_", i)]]) %||% cat_def$levels
      cur_sd  <- isolate(input[[paste0("ef_sd_", i)]])     %||% cat_def$sd
      div(
        class = "facet-card",
        div(
          class = "compact-row",
          div(textInput(paste0("ef_name_", i), sprintf("Facet %d name", i + 2L), value = cur_nm)),
          div(sliderInput(paste0("ef_sd_", i), "SD (logits)", min = 0.10, max = 1.20, value = cur_sd, step = 0.05))
        ),
        sliderInput(paste0("ef_levels_", i), "Number of levels", min = 2, max = 12, value = cur_lvl, step = 1)
      )
    })
    do.call(tagList, cards)
  })

  extra_facets_df <- reactive({
    k <- n_extra()
    if (k == 0L) {
      return(normalize_extra_facets(NULL))
    }
    rows <- lapply(seq_len(k), function(i) {
      cat_def <- if (i <= length(default_facet_catalog)) default_facet_catalog[[i]] else list(name = paste0("Facet", i + 2L), levels = 2L, sd = 0.25)
      data.frame(
        name   = input[[paste0("ef_name_", i)]]   %||% cat_def$name,
        levels = input[[paste0("ef_levels_", i)]] %||% cat_def$levels,
        sd     = input[[paste0("ef_sd_", i)]]     %||% cat_def$sd,
        stringsAsFactors = FALSE
      )
    })
    normalize_extra_facets(do.call(rbind, rows))
  })

  output$stepFacetUI <- renderUI({
    ef <- extra_facets_df()
    choices <- c(ef$name, "Rater")
    selectInput("step_facet", "PCM step-varying facet", choices = choices, selected = choices[1L])
  })

  current_p_vals <- reactive({
    build_p_candidates(input$p_range %||% c(30L, 90L), input$p_points %||% 3L)
  })

  current_grid <- reactive({
    build_candidate_grid(
      p_vals = current_p_vals(),
      r_vals = input$n_rater %||% 6L,
      assignment = input$assignment %||% "rotating",
      raters_per_person = input$raters_per_person %||% 2L,
      anchor_persons = input$anchor_persons %||% 6L,
      extra_facets = extra_facets_df(),
      n_cat = input$n_cat %||% 5L
    )
  })

  output$workloadPreview <- renderUI({
    g  <- current_grid()
    ef <- extra_facets_df()
    fac_Chain <- paste(c("Person", "Rater", ef$name), collapse = " x ")
    tot_rng <- range(g$total_ratings)
    rat_rng <- range(g$ratings_per_rater)
    tot_txt <- if (tot_rng[1] == tot_rng[2]) sprintf("%d", tot_rng[1]) else sprintf("%d-%d", tot_rng[1], tot_rng[2])
    rat_txt <- if (rat_rng[1] == rat_rng[2]) sprintf("%.0f", rat_rng[1]) else sprintf("%.0f-%.0f", rat_rng[1], rat_rng[2])
    cls <- if (max(g$total_ratings) > 25000L) "workload-warn" else "workload-box"
    warn_line <- if (max(g$total_ratings) > 25000L) {
      tags$div(tags$strong("Exceeds interactive limit (25,000 ratings/rep): "), "reduce facet levels or run via Reproducible R Code.")
    } else NULL

    div(
      class = cls,
      tags$strong(sprintf("%d-facet design (%s)", 2L + nrow(ef), fac_Chain)),
      tags$br(),
      sprintf("Candidates P = {%s} | %s ratings (%s / rater)", paste(current_p_vals(), collapse = ", "), tot_txt, rat_txt),
      warn_line
    )
  })

  sim_res <- eventReactive(input$run_btn, {
    g <- current_grid()
    validate(
      need(length(input$methods) > 0L, "Select at least one estimator (MML or JML)."),
      need(max(g$total_ratings) <= 25000L, "Candidate exceeds 25,000 ratings/replicate. Reduce facet levels or use script mode.")
    )
    withProgress(message = "Simulating MFRM designs...", value = 0, {
      run_design_plan(
        grid_df = g,
        methods = input$methods,
        model = input$model,
        step_facet = input$step_facet,
        reps = input$reps %||% 15L,
        sd_person = input$sd_person %||% 1.0,
        sd_rater = input$sd_rater %||% 0.40,
        target_rel = input$target_rel %||% 0.80,
        target_rater_rmse = input$target_rater_rmse %||% 0.20,
        seed = input$seed %||% 2026L,
        progress_cb = function(frac, detail) setProgress(value = frac, detail = detail)
      )
    })
  })

  output$decisionBanner <- renderUI({
    if (input$run_btn == 0L) {
      return(div(
        class = "workload-box",
        "Adjust sliders on the left and click ", tags$strong("Run Simulation"),
        " to compare MML and JML precision against human rating workload."
      ))
    }
    res <- sim_res()
    rec <- res$recommended
    if (!is.null(rec)) {
      div(
        class = "rec-pass",
        tags$strong("Recommended minimum-workload plan: "),
        sprintf(
          "%s with %s (%d total ratings; %.0f per rater) — Person r² = %.2f, Rater RMSE = %.3f logits (%.0f%% valid runs).",
          rec$Plan, rec$Estimator, rec$total_ratings, rec$ratings_per_rater,
          rec$PersonRel, rec$RaterRMSE, rec$ValidPct
        )
      )
    } else {
      div(
        class = "rec-warn",
        tags$strong("No candidate met all thresholds. "),
        "Slide up raters per examinee (or facet levels) to raise Person r², or slide up Examinees P / shared anchors k to lower Rater RMSE."
      )
    }
  })

  output$summaryKable <- renderUI({
    req(input$run_btn > 0L)
    HTML(format_summary_kable(sim_res()))
  })

  output$downloadSummaryUI <- renderUI({
    req(input$run_btn > 0L)
    downloadButton("downloadCSV", "Download Summary (CSV)")
  })

  output$downloadCSV <- downloadHandler(
    filename = function() sprintf("mfrm_design_plan_%s.csv", format(Sys.Date(), "%Y%m%d")),
    content = function(file) utils::write.csv(sim_res()$summary, file, row.names = FALSE)
  )

  output$tradeoffPlotly <- renderPlotly({
    req(input$run_btn > 0L)
    build_tradeoff_plotly(sim_res(), secondary_metric = input$sec_metric)
  })

  output$downloadPlot <- downloadHandler(
    filename = function() sprintf("mfrm_tradeoff_%s.png", format(Sys.Date(), "%Y%m%d")),
    content = function(file) {
      p <- build_tradeoff_ggplot(sim_res(), secondary_metric = input$sec_metric)
      ggsave(file, p, width = 7.6, height = 5.4, dpi = 300, bg = "white")
    }
  )

  code_text <- reactive({
    generate_reproducible_code(
      p_vals = current_p_vals(),
      n_rater = input$n_rater %||% 6L,
      assignment = input$assignment %||% "rotating",
      raters_per_person = input$raters_per_person %||% 2L,
      anchor_persons = input$anchor_persons %||% 6L,
      extra_facets = extra_facets_df(),
      n_cat = input$n_cat %||% 5L,
      methods = input$methods %||% c("MML", "JML"),
      model = input$model %||% "RSM",
      step_facet = input$step_facet,
      reps = input$reps %||% 15L,
      sd_person = input$sd_person %||% 1.0,
      sd_rater = input$sd_rater %||% 0.40,
      target_rel = input$target_rel %||% 0.80,
      target_rater_rmse = input$target_rater_rmse %||% 0.20,
      seed = input$seed %||% 2026L
    )
  })

  output$codeBlock <- renderText(code_text())

  output$downloadCode <- downloadHandler(
    filename = function() "run_mfrm_design_plan.R",
    content = function(file) writeLines(code_text(), con = file)
  )
}

shinyApp(ui = ui, server = server)
